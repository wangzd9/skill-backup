class Diagram:
 def __init__(self,w,h,title,desc):
  self.parts=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-labelledby="title desc">',f'<title id="title">{escape(title)}</title><desc id="desc">{escape(desc)}</desc>', '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="#64748b"/></marker></defs>', '<style>text{font-family:"Noto Sans CJK SC","Microsoft YaHei","PingFang SC",sans-serif;fill:#0f172a}.heading{font-size:21px;font-weight:700}.line{font-size:16px}.note{font-size:14px;fill:#475569}</style>',f'<rect width="{w}" height="{h}" fill="#ffffff" rx="16"/>']
  self.text(32,35,title,'heading')
 def text(self,x,y,s,cls='line'):
  self.parts.append(f'<text x="{x}" y="{y}" class="{cls}">{escape(s)}</text>')
 def box(self,x,y,w,h,title,lines,kind='weak'):
  fill,stroke=COLORS[kind];self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="{fill}" stroke="{stroke}" stroke-width="2"/>')
  self.text(x+18,y+29,title,'heading')
  for i,line in enumerate(lines):self.text(x+18,y+55+i*23,line)
 def arrow(self,points,dash=False):
  pts=' '.join(f'{x},{y}' for x,y in points)
  self.parts.append(f'<polyline points="{pts}" fill="none" stroke="#64748b" stroke-width="2" marker-end="url(#arrow)"'+(' stroke-dasharray="7 5"' if dash else '')+'/>')
 def save(self,name):
  (ROOT/name).write_text('\n'.join(self.parts+['</svg>'])+'\n')

